const I18N = { es: null, en: I18N_EN, pt: I18N_PT };

function i18nCurrentLang() {
    try {
        const saved = localStorage.getItem('ttmLang');
        if (saved && APP_LANGS.indexOf(saved) !== -1) return saved;
    } catch (e) { /* localStorage no disponible */ }
    // Detectar idioma del navegador como default
    try {
        const bl = (navigator.language || '').toLowerCase();
        if (bl.indexOf('en') === 0) return 'en';
        if (bl.indexOf('pt') === 0) return 'pt';
    } catch (e) { /* noop */ }
    return 'es';
}

/**
 * Traduce un texto en español al idioma activo.
 * En español devuelve la clave tal cual; en EN/PT busca en el diccionario
 * y si no encuentra, devuelve la clave (fallback a español).
 */
window.t = function(key) {
    if (key == null) return key;
    const lang = i18nCurrentLang();
    if (lang === 'es') return key;
    const dict = I18N[lang];
    if (dict && typeof dict[key] === 'string') return dict[key];
    return key;
};

// Aplica traducciones a los elementos con data-i18n (texto, título, placeholder)
window.applyI18n = function() {
    const lang = i18nCurrentLang();
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
        el.textContent = window.t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function(el) {
        el.title = window.t(el.getAttribute('data-i18n-title'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
        el.placeholder = window.t(el.getAttribute('data-i18n-placeholder'));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function(el) {
        el.setAttribute('aria-label', window.t(el.getAttribute('data-i18n-aria')));
    });
    try {
        document.documentElement.lang = lang;
    } catch (e) { /* noop */ }
};

window.getLang = function() {
    return i18nCurrentLang();
};

// Locale BCP-47 según el idioma activo (para fechas, horas, etc.)
window.i18nLocale = function() {
    const lang = i18nCurrentLang();
    if (lang === 'en') return 'en-US';
    if (lang === 'pt') return 'pt-BR';
    return 'es-AR';
};

// Hooks para que los componentes en vivo (scoreboard, mesas, modal) se
// re-rendericen al cambiar de idioma. setLang los invoca al final.
window.__langChangeHooks = [];
window.onLangChange = function(fn) {
    window.__langChangeHooks.push(fn);
};

function updateLangButton() {
    const btn = document.getElementById('lang-toggle');
    if (!btn) return;
    const flags = { es: '🌐', en: '🌐', pt: '🌐' };
    const labels = { es: 'ES', en: 'EN', pt: 'PT' };
    const tooltips = {
        es: 'Idioma: Español',
        en: 'Language: English',
        pt: 'Idioma: Português'
    };
    const lang = i18nCurrentLang();
    btn.textContent = flags[lang] || flags.es;
    btn.title = (tooltips[lang] || tooltips.es) + ' (clic para cambiar)';
    // Resaltar idioma activo en el panel
    document.querySelectorAll('.lang-option').forEach(function(opt) {
        opt.classList.remove('active');
        const optLang = opt.textContent.trim().split(' ').pop().toLowerCase();
        if (optLang === lang) opt.classList.add('active');
    });
}

// Cambia el idioma y re-renderiza la pestaña activa para refrescar textos dinámicos
window.setLang = function(lang) {
    if (APP_LANGS.indexOf(lang) === -1) return;
    try {
        localStorage.setItem('ttmLang', lang);
    } catch (e) { /* localStorage no disponible */ }
    applyI18n();
    updateLangButton();
    const active = document.querySelector('.tab.active');
    if (active && typeof showTab === 'function') {
        showTab(active.getAttribute('data-tab'));
    }
    // Re-renderizar componentes en vivo (scoreboard, mesas, modal abierto, etc.)
    (window.__langChangeHooks || []).forEach(function(fn) {
        try { fn(lang); } catch (e) { /* noop */ }
    });
};

// Selector de idioma con banderas (dropdown)
window.toggleLangSelector = function() {
    const panel = document.getElementById('lang-panel');
    if (panel) {
        const isOpen = panel.classList.contains('show');
        panel.classList.toggle('show');
        if (!isOpen) {
            // Cerrar al hacer clic fuera
            setTimeout(function() {
                document.addEventListener('click', window.__closeLangPanel);
            }, 10);
        }
    }
};

window.__closeLangPanel = function(e) {
    const panel = document.getElementById('lang-panel');
    const btn = document.getElementById('lang-toggle');
    if (panel && btn && !panel.contains(e.target) && !btn.contains(e.target)) {
        panel.classList.remove('show');
        document.removeEventListener('click', window.__closeLangPanel);
    }
};

window.setLangAndClose = function(lang) {
    setLang(lang);
    const panel = document.getElementById('lang-panel');
    if (panel) panel.classList.remove('show');
    document.removeEventListener('click', window.__closeLangPanel);
    const msgs = { es: 'Idioma: Español', en: 'Language: English', pt: 'Idioma: Português' };
    if (typeof showToast === 'function') showToast(msgs[lang] || lang, 'info');
};

// Cicla entre los idiomas disponibles (es → en → pt → es) — fallback para compat
window.cycleLang = function() {
    const cur = i18nCurrentLang();
    const next = APP_LANGS[(APP_LANGS.indexOf(cur) + 1) % APP_LANGS.length];
    setLangAndClose(next);
};

// Inicialización al cargar el DOM
document.addEventListener('DOMContentLoaded', function() {
    applyI18n();
    updateLangButton();
});
